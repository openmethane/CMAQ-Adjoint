            DO C = 1, MY_NCOLS
               DO L = 1, ELAYS
                  CNVTR = CNVTE * RDX3F( L ) * RRHOJ( C,R,L )
                  DO V = STRT, FINI
                     VDEMIS( V,L,C,R ) = VDEMIS( V,L,C,R ) * CNVTR
                  END DO
               END DO
            END DO
         END DO
      END IF

