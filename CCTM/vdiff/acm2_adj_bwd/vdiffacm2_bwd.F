      IF ( EM_TRAC .AND. N_TR_EMIS .GT. 0 ) THEN
         CALL RDEMIS_TR ( MDATE, MTIME, ELAYS, N_TR_EMIS, VDEMIS_TR )

         STRT = NEMIS + NEMIS_AE + N_NR_EMIS + 1
         FINI = NEMIS + NEMIS_AE + N_NR_EMIS + N_TR_EMIS
         DO R = 1, MY_NROWS
            DO C = 1, MY_NCOLS
               DO L = 1, ELAYS
                  CNVTR = CNVTE * RDX3F( L ) * RRHOJ( C,R,L )
                  DO V = STRT, FINI
                     S = V + 1 - STRT
                     VDEMIS( V,L,C,R ) = VDEMIS_TR( S,L,C,R ) * CNVTR
                  END DO
               END DO
            END DO
         END DO
      END IF

C zero out emissions values for species not included in diffused list

      DO R = 1, MY_NROWS
         DO C = 1, MY_NCOLS
            DO L = 1, ELAYS
               VDEMIS( N_SPC_EMIS+1,L,C,R ) = 0.0  ! accounts for emissions
            END DO                                 ! species names as a subset
         END DO                                    ! of the vert. diffused
      END DO                                       ! species list

      CALL EDDYX ( JDATE, JTIME, TSTEP( 2 ),
     &             EDDYV, HOL, XPBL, LPBL, CONVCT )

C EDDYV returned = Kz, where Kz is in m**2/sec

      DO R = 1, MY_NROWS
         DO C = 1, MY_NCOLS
            DO L = 1, NLAYS
               SEDDY( L,C,R ) = EDDYV( C,R,L )
     &                        * RVJACMF( C,R,L ) * RDX3M( L ) ! * DELT
            END DO
         END DO
      END DO

      IF ( IFACM .EQ. 0 ) CONVCT = .FALSE.   ! no ACM

C----------------------------------------------
C RESET GLOBAL ADJOINT VARIABLES
C----------------------------------------------
      cngrd_bwd(:,:,:,:) = 0.

C----------------------------------------------
C RESET LOCAL ADJOINT VARIABLES
C----------------------------------------------
      conc_bwd(:,:) = 0.
      dd_bwd(:,:) = 0.
      delc_bwd = 0.
      uu_bwd(:,:) = 0.

C----------------------------------------------
C ROUTINE BODY
C----------------------------------------------
      call rev_cgrid_bwd( cngrd_bwd, mdate, mtime, cgrid_bwd )
      do r = my_nrows, 1, -1
        seddyh(:,:,:) = seddy(:,:,:)
        convcth(:,:) = convct(:,:)
        do c = my_ncols, 1, -1
          convct(:,:) = convcth(:,:)
          seddy(:,:,:) = seddyh(:,:,:)
          do c1 = 1, c-1
            if (convct(c1,r)) then
              lcbl = lpbl(c1,r)
              meddy = seddy(1,c1,r)/(xpbl(c1,r)-x3face_gd(1))
              fnl = 1./(1.+(karman/(-hol(c1,r)))**0.3333/(0.72*karman))
              mbar = meddy*fnl
              do l = 1, lcbl-1
                seddy(l,c1,r) = seddy(l,c1,r)*(1.-fnl)
              end do
              if ( mbar .lt. eps ) then
                 write( logdev,* ) ' EDDYV, MBAR, FNL, HOL = ',
     &                eddyv( c1,r,1 ), mbar, fnl, hol( c1,r )
                 convct( c1,r ) = .false.
                 lcbl = 1
                 xmsg = '*** ACM fails ***'
                 call m3exit( pname, mdate, mtime, xmsg, xstat2 )
              end if
            endif
          end do
          dtlim = dtsec
          do l = 1, nlays-1
            dtlim = min(dtlim,0.75/(seddy(l,c,r)*rdx3f(l)))
          end do
          mbarks = 0.
          mdwn = 0.
          if (convct(c,r)) then
            lcbl = lpbl(c,r)
            meddy = seddy(1,c,r)/(xpbl(c,r)-x3face_gd(1))
            fnl = 1./(1.+(karman/(-hol(c,r)))**0.3333/(0.72*karman))
            mbar = meddy*fnl
            do l = 1, lcbl-1
              seddy(l,c,r) = seddy(l,c,r)*(1.-fnl)
            end do
            if (mbar .lt. eps) then
              convct(c,r) =  .false. 
              lcbl = 1
            endif
            do l = 1, lcbl-1
              mbarks(l) = mbar
              mdwn(l) = mbar*(xpbl(c,r)-x3face_gd(l-1))*rdx3f(l)
            end do
            mbarks(lcbl) = mbar*(xpbl(c,r)-x3face_gd(lcbl-1))*rdx3f(lcbl)
            mdwn(lcbl) = mbarks(lcbl)
            rz = (x3face_gd(lcbl)-x3face_gd(1))*rdx3f(1)
            dtacm = 1./(mbar*rz)
            dtlim = min(0.75*dtacm,dtlim)
          else
            lcbl = 1
          endif
          nlp = int(dtsec/dtlim+0.99)
          dts = dtsec/nlp
          do l = 1, nlays
            eddy(l) = seddy(l,c,r)
          end do
          do v = 1, n_spc_depv
            efac1(v) = exp(-(depv(v,c,r)*rdepvht(c,r)*thbar*dts))
            efac2(v) = exp(-(depv(v,c,r)*rdepvht(c,r)*theta*dts))
          end do
          do l = 1, nlays
            do v = 1, n_spc_diff
              conc_bwd(v,l) = conc_bwd(v,l)+cngrd_bwd(diff_map(v),l,c,r)
              cngrd_bwd(diff_map(v),l,c,r) = 0.
            end do
          end do
          do nl = nlp, 1, -1
            do l = 1, nlays
              aa(l) = 0.
              bb(l) = 0.
              cc(l) = 0.
              ee(l) = 0.
            end do
            if (convct(c,r)) then
              do l = 2, lcbl
                aa(l) = -(crankp*mbarks(l)*dts)
                bb(l) = 1.+crankp*mdwn(l)*dts
                ee(l-1) = -(crankp*mdwn(l)*dts*dx3f(l)*rdx3f(l-1))
              end do
            endif
            aa(2) = aa(2)-eddy(1)*crankp*rdx3f(2)*dts
            ee(1) = ee(1)-eddy(1)*crankp*rdx3f(1)*dts
            do l = 2, nlays
              if (l .gt. lcbl) then
                bb(l) = 1.
              endif
              xplus = eddy(l)*rdx3f(l)*dts
              xminus = eddy(l-1)*rdx3f(l)*dts
              bb(l) = bb(l)+(xplus+xminus)*crankp
              cc(l) = -(xminus*crankp)
              ee(l) = ee(l)-xplus*crankp
            end do
            bb(1) = 1.
            if (convct(c,r)) then
              lfac1 = (xpbl(c,r)-x3face_gd(1))*rdx3f(1)*dts
              bb(1) = bb(1)+crankp*mbarks(1)*lfac1
            endif
            bb(1) = bb(1)+crankp*eddy(1)*rdx3f(1)*dts
            lfac1 = crankq*eddy(1)*rdx3f(1)*dts
            do v = n_spc_depv, 1, -1
              conc_bwd(dv2df(v),1) = conc_bwd(dv2df(v),1)*efac2(v)
            end do
            do l = 1, nlays
              do v = 1, n_spc_diff
                uu_bwd(v,l) = uu_bwd(v,l)+conc_bwd(v,l)
                conc_bwd(v,l) = 0.
              end do
            end do
            if (convct(c,r)) then
              call matrix_bwd( aa,bb,cc,ee,dd_bwd,uu_bwd )
            else
              call tri_bwd( cc,bb,ee,dd_bwd,uu_bwd )
            endif
            do v = 1, n_spc_diff
              conc_bwd(v,2) = conc_bwd(v,2)+dd_bwd(v,1)*lfac1
              conc_bwd(v,1) = conc_bwd(v,1)-dd_bwd(v,1)*lfac1
            end do
            if (convct(c,r)) then
              lfac1 = (xpbl(c,r)-x3face_gd(1))*rdx3f(1)*dts
              lfac2 = crankq*mdwn(2)*dx3f(2)*rdx3f(1)*dts
              lfac1 = crankq*mbarks(1)*lfac1
              do v = 1, n_spc_diff
                conc_bwd(v,2) = conc_bwd(v,2)+dd_bwd(v,1)*lfac2
                conc_bwd(v,1) = conc_bwd(v,1)-dd_bwd(v,1)*lfac1
              end do
            endif
            do v = 1, n_spc_diff
              conc_bwd(v,1) = conc_bwd(v,1)+dd_bwd(v,1)
              dd_bwd(v,1) = 0.
            end do
            do l = 2, nlays
              xplus = eddy(l)*rdx3f(l)*dts
              xminus = eddy(l-1)*rdx3f(l)*dts
              if (l .eq. nlays) then
                do v = 1, n_spc_diff
                  conc_bwd(v,l-1) = conc_bwd(v,l-1)+dd_bwd(v,l)*crankq*xminus
                  conc_bwd(v,l) = conc_bwd(v,l)-dd_bwd(v,l)*crankq*xminus
                end do
              else
                lfac1 = crankq*xplus
                lfac2 = crankq*xminus
                do v = 1, n_spc_diff
                  conc_bwd(v,l-1) = conc_bwd(v,l-1)+dd_bwd(v,l)*lfac2
                  conc_bwd(v,l+1) = conc_bwd(v,l+1)+dd_bwd(v,l)*lfac1
                  conc_bwd(v,l) = conc_bwd(v,l)-dd_bwd(v,l)*(lfac1+lfac2)
                end do
              endif
              if (l .gt. lcbl) then
                do v = 1, n_spc_diff
                  conc_bwd(v,l) = conc_bwd(v,l)+dd_bwd(v,l)
                  dd_bwd(v,l) = 0.
                end do
              endif
            end do
            if (convct(c,r)) then
              do l = 2, lcbl
                delc_bwd = 0.
                mfac = dx3f(l+1)*rdx3f(l)*mdwn(l+1)
                do v = 1, n_spc_diff
                  delc_bwd = 0.
                  conc_bwd(v,l) = conc_bwd(v,l)+dd_bwd(v,l)
                  delc_bwd = delc_bwd+dd_bwd(v,l)*crankq
                  dd_bwd(v,l) = 0.
                  conc_bwd(v,l+1) = conc_bwd(v,l+1)+delc_bwd*dts*mfac
                  conc_bwd(v,l) = conc_bwd(v,l)-delc_bwd*dts*mdwn(l)
                  conc_bwd(v,1) = conc_bwd(v,1)+delc_bwd*dts*mbarks(l)
                  delc_bwd = 0.
                end do
              end do
            endif
            do l = 1, nlays
              do v = 1, n_spc_diff
                dd_bwd(v,l) = 0.
              end do
            end do
            do v = n_spc_depv, 1, -1
              conc_bwd(dv2df(v),1) = conc_bwd(dv2df(v),1)*efac1(v)
            end do
          end do
          do l = 1, nlays
            do v = 1, n_spc_diff
              cngrd_bwd(diff_map(v),l,c,r) = cngrd_bwd(diff_map(v),l,c,r)+conc_bwd(v,l)
              conc_bwd(v,l) = 0.
            end do
          end do
        end do
      end do
      call conv_cgrid_bwd( cgrid_bwd, mdate, mtime, cngrd_bwd )

      end subroutine vdiff_bwd
