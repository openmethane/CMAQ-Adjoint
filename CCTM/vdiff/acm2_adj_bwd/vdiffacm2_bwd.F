      IF ( N_NR_EMIS .GT. 0 ) THEN
         CALL RDEMIS_NR ( MDATE, MTIME, ELAYS, N_NR_EMIS, VDEMIS_NR )

         STRT = NEMIS + NEMIS_AE + 1
         FINI = NEMIS + NEMIS_AE + N_NR_EMIS
         DO R = 1, MY_NROWS
            DO C = 1, MY_NCOLS
               DO L = 1, ELAYS
                  CNVTR = CNVTE * RDX3F( L ) * RRHOJ( C,R,L )
                  DO V = STRT, FINI
                     S = V + 1 - STRT
                     VDEMIS( V,L,C,R ) = VDEMIS_NR( S,L,C,R ) * CNVTR
                  END DO
               END DO
            END DO
         END DO
      END IF

