         STRT = NEMIS + 1
         FINI = NEMIS + NEMIS_AE
         DO R = 1, MY_NROWS
            DO C = 1, MY_NCOLS
               DO L = 1, ELAYS
                  DO V = STRT, FINI
                     S = V + 1 - STRT
                     VDEMIS( V,L,C,R ) = VDEMIS_AE( S,L,C,R )
                  END DO
               END DO
            END DO
         END DO
      END IF

