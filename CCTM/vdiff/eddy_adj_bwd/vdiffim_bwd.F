              bi_bwd(v,l) = 0.
            end do
            l = 1
            do v = 1, n_spc_diff
              conc_bwd(v,l+1) = conc_bwd(v,l+1)+bi_bwd(v,l)*thbar*pk(l)
              conc_bwd(v,l) = conc_bwd(v,l)+bi_bwd(v,l)*(1-thbar*pk(l)-dvb1(v))
              bi_bwd(v,l) = 0.
            end do
